#!/usr/bin/env python3
"""Render a replay.py JSON file as a human-readable Markdown transcript.

  python3 tools/parity/transcript.py docs/migration/baseline/legacy-run.json > docs/migration/baseline/transcripts.md
"""
import json
import sys


def excerpt(resp, limit=420):
    if "json" in resp:
        s = json.dumps(resp["json"], sort_keys=True)
    elif "html" in resp:
        h = resp["html"]
        parts = ["title=%r" % h.get("title")]
        if h.get("alerts"):
            parts.append("alerts=%s" % json.dumps([a for a in h["alerts"] if a]))
        for f in h.get("forms", []):
            names = [x.get("name") for x in f["fields"] if x.get("name")]
            parts.append("form %s %s %s" % (f["method"].upper(), f["action"], names))
        parts.append("text=%r" % (h.get("text") or "")[:200])
        s = " | ".join(parts)
    else:
        s = resp.get("text") or ""
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= limit else s[:limit] + "..."


def main():
    d = json.load(open(sys.argv[1]))
    print("# HTTP transcript: %s\n" % d["meta"].get("label"))
    print("Generated by `tools/parity/transcript.py` from `%s` (normalised values: `{JWT}`, `{TS}`, `{DATE}`, `{ID}`,"
          " `{ACCT:...}` aliases, `{MONEY}` on masked steps). Full structured data (forms with every field, options,"
          " visible text) is in the JSON.\n" % sys.argv[1].split("/")[-1])
    flow = None
    for s in d["steps"]:
        if s["flow"] != flow:
            flow = s["flow"]
            print("\n## %s\n\n| step | request | status | redirect / content-type | body excerpt |\n|---|---|---|---|---|" % flow)
        q = s["request"]
        req = "%s %s%s" % (q["method"], q["base"], q["path"])
        if q.get("params"):
            req += " params=" + json.dumps(q["params"])
        if q.get("form"):
            req += " form=" + json.dumps({k: ("***" if "assword" in k else v) for k, v in q["form"].items()})
        if q.get("json") is not None:
            req += " json=" + json.dumps(q["json"])
        r = s["response"]
        loc = r.get("location") or ""
        if r.get("redirects"):
            loc = " -> ".join("%s %s" % (x["status"], x["location"]) for x in r["redirects"]) + " -> " + str(r["status"])
        print("| `%s` | `%s` | %s | %s %s | %s |" % (s["id"], req.replace("|", "\\|"), r["status"], loc,
                                                  r.get("content_type") or "", excerpt(r)))
    print("\n## DB snapshot (admin REST API after all flows)\n\n```json\n%s\n```" %
          json.dumps({k: v for k, v in d.get("db_snapshot", {}).items() if not k.startswith("bank.users")}, indent=1)[:6000])


if __name__ == "__main__":
    main()
